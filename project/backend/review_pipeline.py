"""Starter module for the Human-in-the-Loop code review pipeline."""


def generate_review(code_snippet: str) -> str:
    """Placeholder function for AI-based review generation."""
    return f"Review generated for snippet: {code_snippet[:80]}"


def integrate_human_feedback(review: str, feedback: str) -> str:
    """Placeholder function for combining AI review with human feedback."""
    return f"{review}\nHuman feedback: {feedback}"